"use client";

import Link from "next/link";
import { Bell, BellOff, FileText, PanelRightClose, UserCheck, Users } from "lucide-react";
import { cn } from "@garageos/design-system";

import type { LinkedCard, ThreadDetail } from "@/lib/api/types";
import { useI18n } from "@/lib/i18n/context";
import { roleColor } from "./shared";

const CARD_ICON: Record<LinkedCard["kind"], string> = {
  case: "🛰️", vehicle: "🚗", customer: "👤", passport: "🏅",
};

// Column 4 — collapsible context. Assigned / Following / Participants are kept
// visually distinct: responsibility vs. subscription vs. who has spoken.
export function ContextPanel({
  thread, actionBlocked, onToggleFollow, onCollapse,
}: {
  thread: ThreadDetail;
  actionBlocked: boolean;
  onToggleFollow: () => void;
  onCollapse: () => void;
}) {
  const { t } = useI18n();
  return (
    <aside className="w-[300px] shrink-0 bg-card border-l border-border overflow-y-auto">
      <div className="flex items-center px-4 h-12 border-b border-border">
        <span className="text-[11px] font-bold uppercase tracking-wider text-muted-foreground">{t("inbox.context.title")}</span>
        <button onClick={onCollapse} className="ml-auto grid min-h-11 min-w-11 place-items-center text-muted-foreground hover:text-foreground focus-visible:outline-2 focus-visible:outline-primary" aria-label={t("inbox.action.close_context")}>
          <PanelRightClose className="size-4" />
        </button>
      </div>

      <div className="p-3 space-y-4">
        {/* Responsibility vs subscription */}
        <div className="grid grid-cols-2 gap-2">
          <div className="rounded-xl border border-border p-2.5">
            <p className="flex items-center gap-1 text-[10px] font-bold uppercase tracking-wide text-muted-foreground mb-1">
              <UserCheck className="size-3" /> {t("inbox.action.assigned")}
            </p>
            <p className="text-[13px] font-semibold text-foreground truncate">
              {thread.assigned_name ?? <span className="text-muted-foreground font-normal">{t("inbox.action.unassigned")}</span>}
            </p>
          </div>
          <button onClick={onToggleFollow} disabled={actionBlocked} aria-label={t(thread.is_following ? "message.following" : "message.follow")}
            className={cn("rounded-xl border p-2.5 text-left transition-colors",
              thread.is_following ? "border-primary/40 bg-primary/5" : "border-border hover:bg-muted/50")}>
            <p className="flex items-center gap-1 text-[10px] font-bold uppercase tracking-wide text-muted-foreground mb-1">
              {thread.is_following ? <Bell className="size-3" /> : <BellOff className="size-3" />} {t("inbox.context.followers")}
            </p>
            <p className={cn("text-[13px] font-semibold", thread.is_following ? "text-primary" : "text-foreground")}>
              {t(thread.is_following ? "message.following" : "message.follow")} · {thread.followers}
            </p>
          </button>
        </div>

        {/* This is a stored record; it is not regenerated by opening the thread. */}
        {thread.ai_summary && (
          <div className="rounded-xl border border-border bg-card p-3">
            <p className="flex items-center gap-1.5 text-[11px] font-bold text-muted-foreground mb-2">
              <FileText className="size-3.5" /> {t("inbox.stored_summary")}
            </p>
            <p className="text-sm font-semibold text-foreground mt-0.5">{thread.ai_summary}</p>
          </div>
        )}

        {/* Linked records */}
        {thread.linked.length > 0 && (
          <div>
            <p className="text-[10px] font-bold uppercase tracking-wide text-muted-foreground mb-2">{t("inbox.linked_records")}</p>
            <div className="space-y-2">
              {thread.linked.map((c) => {
                const title = c.available === false ? t("inbox.linked.vehicle_unavailable")
                  : c.kind === "passport" ? t("inbox.context.passport") : c.title;
                const subtitle = c.kind === "customer" && c.subtitle === "Customer 360"
                  ? t("inbox.context.customer_detail") : c.subtitle;
                const card = (
                  <>
                  <span className={cn("grid size-8 place-items-center rounded-lg text-sm shrink-0",
                    c.kind === "case" ? "bg-red-50" : c.kind === "customer" ? "bg-purple-50" : "bg-amber-50")}>
                    {CARD_ICON[c.kind]}
                  </span>
                  <div className="min-w-0 flex-1">
                    <p className="text-[13px] font-semibold text-foreground truncate">{title}</p>
                    {subtitle && <p className="text-[11px] text-muted-foreground truncate">{subtitle}</p>}
                  </div>
                  {c.link && <span className="text-muted-foreground text-sm">→</span>}
                  </>
                );
                return c.link ? (
                  <Link key={c.kind} href={c.link} target={c.kind === "passport" ? "_blank" : undefined}
                    className="flex items-center gap-2.5 rounded-xl border border-border p-2.5 hover:border-primary/40 hover:bg-muted/30 transition-colors">
                    {card}
                  </Link>
                ) : (
                  <div key={c.kind} role="note" aria-label={title ?? undefined}
                    className="flex items-center gap-2.5 rounded-xl border border-border p-2.5 text-muted-foreground">
                    {card}
                  </div>
                );
              })}
            </div>
          </div>
        )}

        {/* Participants — who has actually spoken */}
        <div>
          <p className="flex items-center gap-1 text-[10px] font-bold uppercase tracking-wide text-muted-foreground mb-2">
            <Users className="size-3" /> {t("inbox.context.participants")}
          </p>
          <div className="space-y-1.5">
            {thread.participants.map((p) => (
              <div key={p.id} className="flex items-center gap-2 text-[13px]">
                <span className="grid size-6 place-items-center rounded-full bg-muted text-[10px] font-bold text-foreground">
                  {p.display_name.split(" ").map((w) => w[0]).join("").slice(0, 2).toUpperCase()}
                </span>
                <span className="flex-1 truncate text-foreground">{p.display_name}</span>
                <span className={cn("text-[10px] capitalize", roleColor(p.role))}>{p.role}</span>
              </div>
            ))}
          </div>
        </div>
      </div>
    </aside>
  );
}
